// Cross-implementation disclosure vectors (§7.7 step 5: "a cross-implementation test vector
// (SDK vs viewer) pins it"). Everything random is pinned, so the viewer can reproduce every
// field byte for byte from `sk` alone.
//
//   node scripts/gen-disclosure-vectors.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { privateKeyToAccount } from 'viem/accounts';
import { deriveDarkKeys } from '../src/keys.ts';
import { deployments } from '../src/deployments.ts';
import { encrypt, hedgedScalar, TAG_TRANSFER_R } from '../src/elgamal.ts';
import {
  buildExactDisclosure, canonicalJson, disclosureContextHash, disclosureDigest, disclosureLink,
  disclosureTypedData, jsonPoint, sealDisclosure, signDisclosure,
} from '../src/disclosure.ts';

const OUT = fileURLToPath(new URL('../test/vectors/disclosure.v2.json', import.meta.url));

const SK = `0x${'11'.repeat(32)}`;
const CHAIN_ID = 46630;
// From the SDK's own deployments table, never a literal: the verifier refuses any document whose
// vault or registry is not `deployments[chainId]`, so a vector minted against a hard-coded address
// silently stops verifying the moment the testnet is redeployed — which is how the whole SDK suite
// went red on 2026-09-20 after the hardened deploy.
const VAULT = deployments[CHAIN_ID].vault;
const REGISTRY = deployments[CHAIN_ID].registry;
const BLOCK = 120_600_000n;
const VALUE = 500_000000n;
const CREATED_AT = 1_789_000_000;
const EXPIRES_AT = CREATED_AT + 30 * 86_400;
const ID = 't_dark1vector';

const hex = (b) => `0x${Buffer.from(b).toString('hex')}`;
const bytes = (fill) => new Uint8Array(32).fill(fill);

const account = privateKeyToAccount(SK);
const keys = deriveDarkKeys(Uint8Array.from(Buffer.from(SK.slice(2), 'hex')), CHAIN_ID);

// The stored `available` ciphertext, with its randomness pinned.
const rho = hedgedScalar(TAG_TRANSFER_R, keys.s, new Uint8Array(8).fill(1), bytes(0xa1));
const e = encrypt(VALUE, [keys.P], rho);
const ciphertext = { c: e.C, d: e.D[0] };

const context = {
  chainId: CHAIN_ID,
  vault: VAULT,
  registry: REGISTRY,
  account: account.address,
  kind: 'balance_exact',
  component: 'available',
  block: BLOCK,
  lo: VALUE,
  hi: VALUE,
  createdAt: CREATED_AT,
  expiresAt: EXPIRES_AT,
  id: ID,
  label: 'Payroll proof of funds',
};

const DLEQ_RAND = bytes(0x7d);
const unsigned = buildExactDisclosure({
  context,
  pk: keys.P,
  ciphertext,
  value: VALUE,
  s: keys.s,
  rand: DLEQ_RAND,
});

const digest = disclosureDigest(unsigned);
const doc = await signDisclosure(unsigned, (td) => account.signTypedData(td));

const BLOB_KEY = bytes(0x3c);
const BLOB_NONCE = new Uint8Array(24).fill(0x9e);
const { blob } = sealDisclosure(doc, ID, BLOB_KEY, BLOB_NONCE);

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      spec: 'DARK-CB-1',
      note: 'Generated by packages/dark-sdk/scripts/gen-disclosure-vectors.mjs. Every random value is pinned.',
      sk: SK,
      chainId: CHAIN_ID,
      account: account.address,
      vault: VAULT,
      registry: REGISTRY,
      s: `0x${keys.s.toString(16).padStart(64, '0')}`,
      pk: jsonPoint(keys.P),
      availRho: `0x${rho.toString(16).padStart(64, '0')}`,
      ciphertext: { c: jsonPoint(ciphertext.c), d: jsonPoint(ciphertext.d) },
      value: VALUE.toString(10),
      version: 2,
      context: { ...context, block: BLOCK.toString(10), lo: VALUE.toString(10), hi: VALUE.toString(10) },
      contextHash: `0x${disclosureContextHash(context).toString(16).padStart(64, '0')}`,
      dleqRand: hex(DLEQ_RAND),
      proof: doc.proof,
      jcsUnsigned: canonicalJson(unsigned),
      digest,
      typedData: JSON.parse(JSON.stringify(
        disclosureTypedData(unsigned),
        (_k, v) => (typeof v === 'bigint' ? v.toString(10) : v),
      )),
      ownerSig: doc.ownerSig,
      jcsSigned: canonicalJson(doc),
      blobKey: hex(BLOB_KEY),
      blobNonce: hex(BLOB_NONCE),
      blob: Buffer.from(blob).toString('base64'),
      link: disclosureLink(ID, BLOB_KEY),
    },
    null,
    2,
  )}\n`,
);
console.log(`wrote ${OUT}`);
