// Emits src/publicInputs.ts from circuits/public_inputs.toml (§6: "the public-input order is
// normative ... generated from circuits/public_inputs.toml"). Run it, commit the result;
// test/publicInputs.test.ts fails if the committed file drifts from a fresh generation.
//
//   node scripts/gen-public-inputs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const TOML = fileURLToPath(new URL('../../../circuits/public_inputs.toml', import.meta.url));
const OUT = fileURLToPath(new URL('../src/publicInputs.ts', import.meta.url));

/** The one shape this file has: `key = value` and `key = [ ... ]` under [table]. */
function readToml(text) {
  const out = {};
  let table = out;
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].replace(/\s*#.*$/, '').trim();
    if (!line) continue;
    const t = line.match(/^\[(.+)\]$/);
    if (t) {
      table = out[t[1]] = {};
      continue;
    }
    const m = line.match(/^(\w+)\s*=\s*(.*)$/);
    if (!m) continue;
    let [, key, value] = m;
    if (value.startsWith('[')) {
      while (!value.includes(']')) value += lines[++i].replace(/\s*#.*$/, '').trim();
      table[key] = [...value.matchAll(/"([^"]*)"/g)].map((x) => x[1]);
    } else if (value.startsWith('"')) table[key] = value.slice(1, value.lastIndexOf('"'));
    else table[key] = value === 'true' ? true : value === 'false' ? false : Number(value);
  }
  return out;
}

const toml = readToml(readFileSync(TOML, 'utf8'));
const circuits = Object.entries(toml).filter(([, v]) => Array.isArray(v?.inputs));

for (const [name, c] of circuits) {
  if (c.inputs.length !== c.count) {
    throw new Error(`${name}: count = ${c.count} but ${c.inputs.length} inputs listed`);
  }
}

const order = circuits
  .map(([n, c]) => `  ${n}: [${c.inputs.map((i) => `'${i}'`).join(', ')}],`)
  .join('\n');
const onchain = circuits.map(([n, c]) => `  ${n}: ${c.onchain},`).join('\n');

writeFileSync(
  OUT,
  `// SPDX-License-Identifier: MIT OR Apache-2.0
// GENERATED by scripts/gen-public-inputs.mjs from circuits/public_inputs.toml. Do not edit.
//
// The canonical public-input order is normative (§6, §19 C1): addresses left-padded uint160,
// everything else a big-endian uint256, each in one bytes32; points are two entries, x then y;
// the identity is (0, 0). The arrays below are exactly what DarkVault/DarkKeyRegistry pass to
// \`IDarkVerifier.verify\`, and \`buildPublicInputs\` is how the SDK re-derives them so it never has
// to trust a proof's own public inputs (§7 "the SDK re-derives the public inputs").
import { DarkError } from './errors.ts';
import type { CircuitId, Hex } from './prover.ts';

export const SPEC_VERSION = '${toml.spec}';

/** Wire public inputs per circuit, in order (§19 X2: wire count, not the VK's publicInputsSize). */
export const publicInputOrder = {
${order}
} as const satisfies Record<CircuitId, readonly string[]>;

/** Which circuits have a deployed Solidity verifier. */
export const publicInputOnchain = {
${onchain}
} as const satisfies Record<CircuitId, boolean>;

export const publicInputCount = Object.fromEntries(
  Object.entries(publicInputOrder).map(([k, v]) => [k, v.length]),
) as Record<CircuitId, number>;

/** A field, an address, or a point that supplies its \`.x\`/\`.y\` entries. */
export type PublicInputValue = bigint | number | string | { x: bigint | string; y: bigint | string };

const MAX_WORD = 1n << 256n;

function toWord(circuit: CircuitId, name: string, v: bigint | number | string): Hex {
  const n = typeof v === 'bigint' ? v : BigInt(v);
  if (n < 0n || n >= MAX_WORD) {
    throw new DarkError('PUBLIC_INPUT_MISMATCH', \`\${circuit}.\${name} does not fit a bytes32\`, { name, value: String(v) });
  }
  return \`0x\${n.toString(16).padStart(64, '0')}\`;
}

/**
 * Build a circuit's \`bytes32[]\` exactly as the contracts pass it. Keys are the
 * \`public_inputs.toml\` names; a dotted name may instead come from an object under its
 * base name, so a witness record with \`pk: {x, y}\` supplies \`pk.x\` and \`pk.y\`.
 */
export function buildPublicInputs(
  circuit: CircuitId,
  fields: Record<string, unknown>,
): Hex[] {
  return publicInputOrder[circuit].map((name) => {
    let v = fields[name];
    const dot = name.indexOf('.');
    if (v === undefined && dot > 0) {
      const base = fields[name.slice(0, dot)];
      if (base && typeof base === 'object') v = (base as Record<string, unknown>)[name.slice(dot + 1)];
    }
    if (v === undefined || v === null || typeof v === 'object') {
      throw new DarkError('PUBLIC_INPUT_MISMATCH', \`\${circuit}: missing public input \${name}\`, { name });
    }
    return toWord(circuit, name, v as bigint | number | string);
  });
}

/** Throws unless \`got\` matches \`want\` word for word. How a prover's output is checked. */
export function assertPublicInputsEqual(circuit: CircuitId, got: readonly string[], want: readonly Hex[]): void {
  const norm = (h: string) => h.toLowerCase();
  if (got.length !== want.length || got.some((g, i) => norm(g) !== norm(want[i]))) {
    throw new DarkError('PUBLIC_INPUT_MISMATCH', \`\${circuit}: prover public inputs differ from the SDK's\`, {
      circuit,
      got: got.map(norm),
      want: want.map(norm),
    });
  }
}
`,
);
console.log(`wrote ${OUT} (${circuits.length} circuits)`);
